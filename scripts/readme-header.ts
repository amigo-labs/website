// Writes the same README header into every project: the pixel monogram, the
// name and one row of badges. The badges read amigo-labs.dev (status, release,
// license, site — src/pages/badges/) and GitHub Actions (CI), so the header
// never needs editing when a project changes; rerun this only to change the
// header itself.
//
//   node scripts/readme-header.ts <owner/repo> [--write path/to/README.md]
//
// Without --write it prints the block. With --write it replaces the block
// between the markers in that README, or, the first time, the README's
// leading "# Title" line (or nothing) with the block. The CI badge is added
// when the README's repository has .github/workflows/ci.yml, the license badge
// links to LICENSE when that file exists.

import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { readProjectFile } from './project-file.ts';

const args = process.argv.slice(2);
const repo = args[0];
const writeIdx = args.indexOf('--write');
const target = writeIdx >= 0 ? args[writeIdx + 1] : undefined;
if (!repo || !/^[\w.-]+\/[\w.-]+$/.test(repo) || (writeIdx >= 0 && !target)) {
  console.error('usage: node scripts/readme-header.ts <owner/repo> [--write path/to/README.md]');
  process.exit(2);
}

const BEGIN = '<!-- amigo-labs header: generated by amigo-labs/website scripts/readme-header.ts -->';
const END = '<!-- /amigo-labs header -->';

const file = await readProjectFile(target ? join(dirname(target), 'docs/site/project.yml') : repo);
const dir = target ? dirname(target) : undefined;
const hasCi = dir ? existsSync(join(dir, '.github/workflows/ci.yml')) : true;
const hasLicense = dir ? existsSync(join(dir, 'LICENSE')) : true;

const site = `https://amigo-labs.dev/${file.slug}/`;
const gh = `https://github.com/${repo}`;
const endpoint = (kind: string) =>
  `https://img.shields.io/endpoint?url=${encodeURIComponent(`https://amigo-labs.dev/badges/${file.slug}/${kind}.json`)}&style=flat-square`;
const link = (href: string | undefined, src: string, alt: string) =>
  href ? `  <a href="${href}"><img src="${src}" alt="${alt}"></a>` : `  <img src="${src}" alt="${alt}">`;

const badges = [
  link(site, endpoint('status'), 'Status'),
  link(`${gh}/releases`, endpoint('version'), 'Release'),
  hasCi
    ? link(
        `${gh}/actions/workflows/ci.yml`,
        `https://img.shields.io/github/actions/workflow/status/${repo}/ci.yml?branch=main&style=flat-square&label=CI`,
        'CI',
      )
    : undefined,
  link(hasLicense ? `${gh}/blob/main/LICENSE` : undefined, endpoint('license'), 'License'),
  link(site, endpoint('site'), 'amigo-labs.dev'),
].filter((b) => b !== undefined);

const block = [
  BEGIN,
  '<p align="center">',
  `  <a href="${site}"><img src="assets/brand/icon-128.png" width="128" height="128" alt=""></a>`,
  '</p>',
  '',
  `<h1 align="center">${file.name}</h1>`,
  '',
  '<p align="center">',
  ...badges,
  '</p>',
  END,
].join('\n');

if (!target) {
  console.log(block);
} else {
  const readme = existsSync(target) ? await readFile(target, 'utf8') : '';
  let next: string;
  const b = readme.indexOf(BEGIN);
  const e = readme.indexOf(END);
  if (b >= 0 && e > b) next = readme.slice(0, b) + block + readme.slice(e + END.length);
  else if (/^# .*\n/.test(readme)) next = readme.replace(/^# .*\n/, `${block}\n`);
  else next = `${block}\n\n${readme}`;
  await writeFile(target, next);
  console.log(`${file.name}: header → ${target}`);
}
